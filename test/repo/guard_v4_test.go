//
// Threat model (§3): prevent ACCIDENTAL private-capability leakage, forbidden
// dependencies and forbidden build inputs. It cannot recognize fully
// renamed/rewritten algorithms — that residual is documented, not claimed.
//
// Layers (each backed by Go tooling, not fragile regex):
//
//   L1 package allowlist      — normalized comparison (V3B-6)
//   L2 AST import guard       — go/parser: alias/blank/dot/grouped/
//                               single-line/build-tag-excluded files all
//                               parsed (V3B-7)
//   L3 build-constraint guard — go/build/constraint legal parse of
//                               //go:build AND legacy // +build, AND/OR/NOT,
//                               parentheses; atom allowlist (V3B-1/V3B-2)
//   L4 private-scope markers  — normalized identifier matching (V3B-8)
//   L5 module law             — no replace, no go.work, no nested go.mod,
//                               pinned requires
//   L6 tree law               — no symlinks, no vendor/

