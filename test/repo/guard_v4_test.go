// normalizeIdent: lowercase and strip _/- separators — marker/allowlist
// matching is done on the normalized form (V3B-6/V3B-8).
func normalizeIdent(s string) string {
	s = strings.ToLower(s)
	s = strings.ReplaceAll(s, "_", "")
	s = strings.ReplaceAll(s, "-", "")
	s = strings.ReplaceAll(s, ".", "")
	return s
}

