// firstPartyRelDirs walks the module and returns (goPackageDirs relative,
// symlinkPaths, goFilesRel, trackedNonVendoredPaths) — symlinks are reported
// and never followed; vendor/ must not exist at all.
func firstPartyScan(t *testing.T, root string) (dirs map[string]bool, symlinks []string, goFiles []string, allFiles []string) {
	dirs = map[string]bool{}
	err := filepath.WalkDir(root, func(p string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, rerr := filepath.Rel(root, p)
		if rerr != nil {
			return nil
		}
		rel = filepath.ToSlash(rel)
		if rel == "." {
			return nil
		}
		if d.IsDir() {
			name := d.Name()
			if name == "vendor" {
				t.Errorf("GUARD-V3 family-4: vendor/ directory present in the public module (untracked build input, not an OSS source of truth)")
				return filepath.SkipDir
			}
			if name == ".git" || name == "bin" || name == "dist" {
				return filepath.SkipDir
			}
			return nil
		}
		if d.Type()&os.ModeSymlink != 0 {
			symlinks = append(symlinks, rel)
			return nil // never follow (§185 law)
		}
		allFiles = append(allFiles, rel)
		if strings.HasSuffix(p, ".go") {
			goFiles = append(goFiles, rel)
			dirs[filepath.ToSlash(filepath.Dir(rel))] = true
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk: %v", err)
	}
	return dirs, symlinks, goFiles, allFiles
}

func TestV3NoSymlinksInTrackedTree(t *testing.T) {
	root := repoRoot(t)
	_, symlinks, _, _ := firstPartyScan(t, root)
	if len(symlinks) > 0 {
		sort.Strings(symlinks)
		t.Fatalf("GUARD-V3 family-1: symlinks are forbidden in the tracked source tree (bypass vector: symlinked packages): %v", symlinks)
	}
}

func TestV3PackageAllowlist(t *testing.T) {
	root := repoRoot(t)
	dirs, _, _, _ := firstPartyScan(t, root)
	var outOfScope []string
	for p := range dirs {
		if !allowedFirstPartyPackages[p] {
			outOfScope = append(outOfScope, p)
		}
	}
	if len(outOfScope) > 0 {
		sort.Strings(outOfScope)
		t.Fatalf("GUARD-V3: out-of-scope first-party packages: %v — extend the allowlist only via the component registry (capability: cleanup.policy)", outOfScope)
	}
}

func TestV3BuildTagAllowlist(t *testing.T) {
	root := repoRoot(t)
	_, _, goFiles, _ := firstPartyScan(t, root)
	for _, rel := range goFiles {
		if strings.HasSuffix(rel, "test/repo/guard_v3_test.go") {
			continue // this guard's own tables are not build-tag violations
		}
		raw, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			continue
		}
		for _, line := range strings.Split(string(raw), "\n") {
			line = strings.TrimSpace(line)
			if !strings.HasPrefix(line, "//go:build") {
				continue
			}
			for _, tag := range strings.Fields(strings.TrimPrefix(line, "//go:build")) {
				clean := strings.Trim(tag, "!")
				if clean == "" || strings.ContainsAny(clean, "()&|") {
					continue // expressions judged by their atoms
				}
				if !allowedBuildTags[clean] {
					t.Errorf("GUARD-V3 family-2: build tag %q in %s is outside the declared tag allowlist (bypass vector: tag-excluded private source)", clean, rel)
				}
			}
		}
	}
}

func TestV3NoPrivateScopeIdentifiers(t *testing.T) {
	root := repoRoot(t)
	_, _, _, allFiles := firstPartyScan(t, root)
	for _, rel := range allFiles {
		if strings.HasSuffix(rel, "test/repo/guard_v3_test.go") {
			continue // this guard's own identifier tables are not leaks
		}
		switch {
		case strings.HasSuffix(rel, ".go"),
			strings.HasSuffix(rel, ".yaml"), strings.HasSuffix(rel, ".yml"),
			strings.HasSuffix(rel, ".json"), strings.HasSuffix(rel, ".md"):
			raw, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
			if err != nil {
				continue
			}
			lower := strings.ToLower(string(raw))
			for _, id := range privateScopeIdentifiers {
				if strings.Contains(lower, strings.ToLower(id)) {
					t.Errorf("GUARD-V3 family-3: private-product scope identifier %q found in %s (bypass vector: content smuggled into allowed dirs / embedded YAML/CRD/docs)", id, rel)
				}
			}
		}
	}
}

