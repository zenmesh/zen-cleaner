func TestV3ImportsResolveToPinnedModules(t *testing.T) {
	root := repoRoot(t)
	gomod, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	// Pinned third-party set = exactly the go.mod require block.
	pinned := map[string]bool{}
	inRequire := false
	for _, line := range strings.Split(string(gomod), "\n") {
		l := strings.TrimSpace(line)
		if strings.HasPrefix(l, "require (") {
			inRequire = true
			continue
		}
		if inRequire && l == ")" {
			inRequire = false
			continue
		}
		if inRequire {
			fields := strings.Fields(l)
			if len(fields) >= 1 {
				pinned[fields[0]] = true
			}
		}
	}
	const self = "github.com/zenmesh/zen-cleaner"
	_, _, goFiles, _ := firstPartyScan(t, root)
	for _, rel := range goFiles {
		if strings.HasSuffix(rel, "test/repo/guard_v3_test.go") {
			continue // this guard's own tables are not imports
		}
		raw, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			continue
		}
		for _, imp := range importSpecs(string(raw)) {
			if strings.HasPrefix(imp, self) {
				continue // own module
			}
			if pinned[imp] || pinnedModuleOf(pinned, imp) != "" {
				continue
			}
			if isStdlib(imp) {
				continue
			}
			t.Errorf("GUARD-V3 family-5: %s imports %q which is neither self, pinned in go.mod, nor stdlib (bypass vector: foreign module path carrying private code)", rel, imp)
		}
	}
}

// importSpecs extracts import paths from a Go source file: both single-line
// `import "x"` and block `import ( ... )` forms (string content elsewhere in
// the file is never mistaken for an import).
func importSpecs(src string) []string {
	var out []string
	lines := strings.Split(src, "\n")
	inBlock := false
	for _, line := range lines {
		l := strings.TrimSpace(line)
		if inBlock {
			if strings.HasPrefix(l, ")") {
				inBlock = false
				continue
			}
			if l == "" || strings.HasPrefix(l, "//") {
				continue
			}
			l = strings.TrimPrefix(l, "_ ")
			l = strings.TrimPrefix(l, "alias ")
			// after optional name: a quoted path
			if i := strings.Index(l, "\""); i >= 0 {
				if j := strings.LastIndex(l, "\""); j > i {
					out = append(out, l[i+1:j])
				}
			}
			continue
		}
		if strings.HasPrefix(l, "import (") {
			inBlock = true
			continue
		}
		if strings.HasPrefix(l, "import ") && strings.Contains(l, "\"") {
			i := strings.Index(l, "\"")
			j := strings.LastIndex(l, "\"")
			if j > i {
				out = append(out, l[i+1:j])
			}
		}
	}
	return out
}

// pinnedModuleOf returns the pinned module that prefixes imp ("" if none).
func pinnedModuleOf(pinned map[string]bool, imp string) string {
	best := ""
	for mod := range pinned {
		if (imp == mod || strings.HasPrefix(imp, mod+"/")) && len(mod) > len(best) {
			best = mod
		}
	}
	return best
}

// isStdlib: conservative standard-library check (no dots in the first path
// element beyond the bare name).
func isStdlib(imp string) bool {
	first := imp
	if i := strings.Index(imp, "/"); i >= 0 {
		first = imp[:i]
	}
	return !strings.Contains(first, ".")
}
